"""Geographic areas (districts and nearby day-trip zones) inside each hotspot city.

Every hotspot is assigned to an area purely from its coordinates: an area is a
circle (center + radius) and a hotspot belongs to the circle that contains it with
the smallest ``distance / radius`` ratio, ties going to catalog order. A place that
falls outside every circle of its city keeps no area rather than being stretched into
the nearest one, so a 30 km day trip never shows up as "新宿".

Radii follow two rules of thumb: 1-3 km for urban districts, 5-20 km for reviewed
suburban or day-trip zones. Area names align with the lodging areas exposed by
``app.destinations.catalog`` where the two overlap.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from decimal import Decimal

from app.hotspots.discovery import haversine_km
from app.i18n import Locale


@dataclass(frozen=True)
class HotspotArea:
    code: str
    names: Mapping[Locale, str]
    latitude: float
    longitude: float
    radius_km: float


def _area(
    code: str,
    zh: str,
    en: str,
    latitude: float,
    longitude: float,
    radius_km: float,
    *,
    ja: str | None = None,
    ko: str | None = None,
) -> HotspotArea:
    names: dict[Locale, str] = {"zh-TW": zh, "en": en}
    if ja:
        names["ja"] = ja
    if ko:
        names["ko"] = ko
    return HotspotArea(code, names, latitude, longitude, radius_km)


