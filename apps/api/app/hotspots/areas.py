AREAS_BY_CODE: dict[str, dict[str, HotspotArea]] = {
    city_code: {area.code: area for area in areas} for city_code, areas in HOTSPOT_AREAS.items()
}


def city_areas(city_code: str | None) -> tuple[HotspotArea, ...]:
    if not city_code:
        return ()
    return HOTSPOT_AREAS.get(city_code.upper(), ())


def area_by_code(city_code: str | None, code: str | None) -> HotspotArea | None:
    if not city_code or not code:
        return None
    return AREAS_BY_CODE.get(city_code.upper(), {}).get(code)


def resolve_area(
    city_code: str | None,
    latitude: float | Decimal | None,
    longitude: float | Decimal | None,
) -> HotspotArea | None:
    """Pick the area whose circle contains the point with the tightest fit."""

    if latitude is None or longitude is None:
        return None
    lat, lon = float(latitude), float(longitude)
    best: HotspotArea | None = None
    best_ratio = float("inf")
    for area in city_areas(city_code):
        distance = haversine_km(lat, lon, area.latitude, area.longitude)
        if distance > area.radius_km:
            continue
        ratio = distance / area.radius_km
        if ratio < best_ratio:
            best, best_ratio = area, ratio
    return best


def resolve_area_code(
    city_code: str | None,
    latitude: float | Decimal | None,
    longitude: float | Decimal | None,
) -> str | None:
    area = resolve_area(city_code, latitude, longitude)
    return area.code if area else None


