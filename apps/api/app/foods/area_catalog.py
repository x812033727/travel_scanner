AREA_SEEDS_BY_SLUG: dict[str, AreaSeed] = {seed.slug: seed for seed in AREA_SEEDS}


def area_seed_for(destination_id: str, source_name: str) -> AreaSeed | None:
    for seed in AREA_SEEDS:
        if seed.destination_id == destination_id and seed.source_name == source_name:
            return seed
    return None


def validate_area_catalog() -> None:
    if len(AREA_SEEDS) != 132:
        raise RuntimeError("area catalog must contain exactly 132 areas")
    slugs = [seed.slug for seed in AREA_SEEDS]
    if len(set(slugs)) != len(slugs):
        raise RuntimeError("area slugs must be unique")
    for seed in AREA_SEEDS:
        if destination_for_id(seed.destination_id) is None:
            raise RuntimeError(f"area {seed.slug} references unknown destination")
        if not SLUG_PATTERN.match(seed.key) or not SLUG_PATTERN.match(seed.slug):
            raise RuntimeError(f"area {seed.slug} must use a lowercase kebab-case key")
        validate_names(seed.names)
        if "／" in seed.source_name and " / " not in seed.names["en"]:
            raise RuntimeError(
                f"combined area {seed.slug} must keep both parts in its English name"
            )
        if seed.center is not None:
            latitude, longitude = seed.center
            if not (-90 <= latitude <= 90 and -180 <= longitude <= 180):
                raise RuntimeError(f"area {seed.slug} has an out-of-range center")
    seeded_pairs = {(seed.destination_id, seed.source_name) for seed in AREA_SEEDS}
    profile_pairs = {
        (profile.id, area) for profile in DESTINATIONS for area in profile.areas
    }
    if seeded_pairs != profile_pairs:
        missing = sorted(profile_pairs - seeded_pairs)
        extra = sorted(seeded_pairs - profile_pairs)
        raise RuntimeError(
            f"area catalog drifted from DestinationProfile.areas: missing={missing} extra={extra}"
        )
    for profile in DESTINATIONS:
        orders = [
            seed.display_order
            for seed in AREA_SEEDS
            if seed.destination_id == profile.id
        ]
        if len(set(orders)) != len(orders):
            raise RuntimeError(
                f"area display orders must be unique within {profile.id}"
            )


validate_area_catalog()
