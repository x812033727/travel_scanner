"""Sub-city areas (商圈) used to browse the merchant directory.

Every ``DestinationProfile.areas`` string has exactly one seed here; the validator
keeps the two lists in lock-step so a renamed profile area fails at import time
instead of silently orphaning merchants. Areas created later from the admin
panel live only in the database and are not covered by this catalog.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass

from app.destinations.catalog import DESTINATIONS, destination_for_id
from app.foods.category_catalog import SLUG_PATTERN, validate_names


@dataclass(frozen=True)
class AreaSeed:
    destination_id: str
    key: str
    names: Mapping[str, str]
    match_terms: tuple[str, ...] = ()
    center: tuple[float, float] | None = None
    display_order: int = 100

    @property
    def slug(self) -> str:
        return f"{self.destination_id}-{self.key}"

    @property
    def source_name(self) -> str:
        return self.names["zh-TW"]


def _a(
    destination_id: str,
    key: str,
    zh_tw: str,
    en: str,
    ja: str,
    ko: str,
    zh_cn: str | None = None,
    *,
    order: int,
    terms: tuple[str, ...] = (),
    center: tuple[float, float] | None = None,
) -> AreaSeed:
    return AreaSeed(
        destination_id=destination_id,
        key=key,
        names={"zh-TW": zh_tw, "zh-CN": zh_cn or zh_tw, "en": en, "ja": ja, "ko": ko},
        match_terms=terms,
        center=center,
        display_order=order,
    )


