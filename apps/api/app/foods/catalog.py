def validate_catalog() -> None:
    if len(FOOD_SEEDS) != 70:
        raise RuntimeError(f"food bootstrap must contain exactly 70 rows, found {len(FOOD_SEEDS)}")
    if len({item.slug for item in FOOD_SEEDS}) != len(FOOD_SEEDS):
        raise RuntimeError("food bootstrap slugs must be unique")
    supported = set(COUNTRY_NAMES)
    counts = {code: sum(item.country_code == code for item in FOOD_SEEDS) for code in supported}
    if any(value != 10 for value in counts.values()):
        raise RuntimeError(f"food bootstrap must contain ten foods per country: {counts}")
    destination_ids = {
        item
        for food in FOOD_SEEDS
        for item in food.destination_ids
        if destination_for_id(item) is None
    }
    if destination_ids:
        raise RuntimeError(f"food bootstrap has unknown destinations: {sorted(destination_ids)}")
    if any(set(item.localized_names) != set(LOCALES) for item in FOOD_SEEDS):
        raise RuntimeError("food bootstrap must contain all public locales")
    if any(not item.source_urls or not item.destination_ids for item in FOOD_SEEDS):
        raise RuntimeError("food bootstrap sources and destinations are required")
    for code in supported:
        if len({item.food_kind for item in FOOD_SEEDS if item.country_code == code}) < 3:
            raise RuntimeError(f"{code} must cover at least three food kinds")


validate_catalog()
