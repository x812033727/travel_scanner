@dataclass(frozen=True)
class FoodSeed:
    slug: str
    country_code: str
    name: str
    simplified_name: str
    local_name: str
    romanized_name: str
    food_kind: str
    meal_types: tuple[str, ...]
    ingredient_tags: tuple[str, ...]
    dietary_notes: tuple[str, ...]
    destination_ids: tuple[str, ...]
    description: str
    wikipedia_title: str
    display_order: int

    @property
    def source_urls(self) -> tuple[str, ...]:
        return (
            OFFICIAL_FOOD_SOURCES[self.country_code],
            f"https://en.wikipedia.org/wiki/{quote(self.wikipedia_title.replace(' ', '_'))}",
        )

    @property
    def localized_names(self) -> dict[str, str]:
        return {
            "zh-TW": self.name,
            "zh-CN": self.simplified_name,
            "en": self.romanized_name,
            "ja": self.local_name if self.country_code == "JP" else self.romanized_name,
            "ko": self.local_name if self.country_code == "KR" else self.romanized_name,
        }

    @property
    def localized_summaries(self) -> dict[str, str]:
        country = COUNTRY_NAMES[self.country_code]
        return {
            "zh-TW": self.description,
            "zh-CN": (
                f"{self.simplified_name}是{country['zh-CN']}具代表性的地方美食，"
                "可在推荐城市的市场或传统街区品尝。"
            ),
            "en": (
                f"{self.romanized_name} is a representative food of {country['en']}, "
                "best explored through approved local markets and food districts."
            ),
            "ja": (
                f"{self.localized_names['ja']}は{country['ja']}を代表する料理で、"
                "現地の市場や食文化地区で楽しめます。"
            ),
            "ko": (
                f"{self.localized_names['ko']}은(는) {country['ko']}을 대표하는 음식으로, "
                "현지 시장과 음식 거리에서 경험할 수 있습니다."
            ),
        }

    @property
    def search_text(self) -> str:
        destinations = [destination_for_id(item) for item in self.destination_ids]
        return " ".join(
            [
                self.slug,
                self.country_code,
                self.local_name,
                self.romanized_name,
                *self.localized_names.values(),
                *(item.city for item in destinations if item is not None),
                *self.ingredient_tags,
            ]
        ).casefold()


def _food(
    slug: str,
    country: str,
    name: str,
    simplified: str,
    local: str,
    romanized: str,
    kind: str,
    meals: tuple[str, ...],
    ingredients: tuple[str, ...],
    destinations: tuple[str, ...],
    description: str,
    wiki: str,
    order: int,
    notes: tuple[str, ...] = (),
) -> FoodSeed:
    return FoodSeed(
        slug,
        country,
        name,
        simplified,
        local,
        romanized,
        kind,
        meals,
        ingredients,
        notes,
        destinations,
        description,
        wiki,
        order,
    )


