#!/usr/bin/env python3
"""Original offline STL acceptance demo. No model/API/tokenizer/paid calls.
This evaluates real local editorial fixture files; it does not evaluate Kimi.
Use --stl part.stl --spec spec.json to inspect another ASCII STL with explicit units/spec.
"""
import argparse,json,math,hashlib
from collections import Counter
from pathlib import Path
BASE=Path(__file__).parent

def sub(a,b):return tuple(x-y for x,y in zip(a,b))
def cross(a,b):return(a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0])
def dot(a,b):return sum(x*y for x,y in zip(a,b))
def geometry(R,r,H,n):
 tris=[]
 def p(radius,i,z):return(radius*math.cos(2*math.pi*i/n),radius*math.sin(2*math.pi*i/n),z)
 for i in range(n):
  j=(i+1)%n;bi,bj,ti,tj=p(R,i,0),p(R,j,0),p(R,i,H),p(R,j,H)
  tris += [(bi,bj,tj),(bi,tj,ti)]
  if r:
   ib,ij,it,jt=p(r,i,0),p(r,j,0),p(r,i,H),p(r,j,H)
   tris += [(ib,it,jt),(ib,jt,ij),(ti,tj,jt),(ti,jt,it),(bi,ib,ij),(bi,ij,bj)]
  else:tris += [((0.,0.,H),ti,tj),((0.,0.,0.),bj,bi)]
 return tris

def write_stl(file,tris):
 rows=['solid editorial_fixture_not_Kimi_output']
 for tri in tris:
  normal=cross(sub(tri[1],tri[0]),sub(tri[2],tri[0]));length=math.sqrt(dot(normal,normal));normal=tuple(x/length for x in normal)
  rows += [' facet normal '+' '.join(f'{x:.12g}' for x in normal),'  outer loop']
  rows += ['   vertex '+' '.join(f'{x:.12g}' for x in v) for v in tri]
  rows += ['  endloop',' endfacet']
 rows += ['endsolid editorial_fixture_not_Kimi_output']
 file.write_text('\n'.join(rows)+'\n')

def read_ascii(file):
 vertices=[]
 for line in file.read_text().splitlines():
  fields=line.split()
  if fields and fields[0]=='vertex':
   if len(fields)!=4:raise ValueError('Malformed vertex')
   v=tuple(float(x) for x in fields[1:]);assert all(math.isfinite(x) for x in v);vertices.append(v)
 if len(vertices)%3 or not vertices:raise ValueError('ASCII STL must contain complete triangles')
 return [tuple(vertices[i:i+3]) for i in range(0,len(vertices),3)]

def ray_hit_z(tri,x,y):
 # Moller-Trumbore, a +Z ray from below the spec plane; no visual inference.
 origin=(x,y,-1.);direction=(0.,0.,1.);a,b,c=tri;e1,e2=sub(b,a),sub(c,a);h=cross(direction,e2);det=dot(e1,h)
 if abs(det)<1e-10:return None
 inv=1/det;s=sub(origin,a);u=inv*dot(s,h)
 if u < -1e-9 or u > 1+1e-9:return None
 q=cross(s,e1);v=inv*dot(direction,q)
 if v < -1e-9 or u+v > 1+1e-9:return None
 t=inv*dot(e2,q)
 return origin[2]+t if t>=0 else None

def audit(file,spec):
 if spec.get('declared_unit')!='mm':raise ValueError('Explicit mm declaration required; STL itself does not encode units')
 tris=read_ascii(file);verts=[v for t in tris for v in t];bounds=[[min(v[d] for v in verts),max(v[d] for v in verts)] for d in range(3)]
 edges=Counter();directions=Counter();degenerate=0
 for a,b,c in tris:
  if math.sqrt(dot(cross(sub(b,a),sub(c,a)),cross(sub(b,a),sub(c,a))))<1e-10:degenerate+=1
  for p,q in [(a,b),(b,c),(c,a)]:
   p,q=tuple(round(x,8) for x in p),tuple(round(x,8) for x in q);key=tuple(sorted((p,q)));edges[key]+=1;directions[key]+=(1 if p<q else -1)
 volume=sum(dot(a,cross(b,c))/6 for a,b,c in tris)
 radius=spec['through_hole_diameter_mm']/2
 probes=[(.137,.193)]+[(radius*.98*math.cos(2*math.pi*i/32),radius*.98*math.sin(2*math.pi*i/32)) for i in range(32)]
 blocked=sum(any(z is not None and -1e-6<=z<=spec['height_mm']+1e-6 for z in (ray_hit_z(t,*p) for t in tris)) for p in probes)
 outer=spec['outer_diameter_mm']/2;expected=math.pi*(outer**2-radius**2)*spec['height_mm'];volume_error=abs(volume-expected)/expected
 checks={'explicit_unit_declaration':True,'edge_manifold':all(c==2 for c in edges.values()),'consistent_edge_winding':all(c==0 for c in directions.values()),'no_degenerate_triangles':degenerate==0,'positive_signed_volume':volume>0,'bounding_dimensions':all(abs((bounds[i][1]-bounds[i][0])-want)<=.001 for i,want in enumerate([spec['outer_diameter_mm'],spec['outer_diameter_mm'],spec['height_mm']])),'specified_axis_hole_open_at33_rays':blocked==0,'volume_within_1percent_of_spec':volume_error<=.01}
 return {'file':str(file),'sha256':hashlib.sha256(file.read_bytes()).hexdigest(),'bytes':file.stat().st_size,'triangles':len(tris),'bounds_in_declared_mm':bounds,'signed_mesh_volume_mm3':volume,'analytic_spec_volume_mm3':expected,'relative_volume_error':volume_error,'blocked_hole_probe_rays':blocked,'hole_probe_count':len(probes),'checks':checks,'accepted_for_this_limited_spec':all(checks.values()),'limits':['STL has no intrinsic unit label: mm is an external explicit spec declaration.','33 vertical rays are a bounded opening check, not proof of an arbitrary curved bore or minimum wall thickness.','No self-intersection, material, slicer, strength or 3D printer validation; a pass is not manufacturing certification.','These fixtures are generated by this deterministic editorial Python program, never by Kimi.']}

def main():
 p=argparse.ArgumentParser();p.add_argument('--stl',type=Path);p.add_argument('--spec',type=Path);p.add_argument('--make-fixtures',action='store_true');a=p.parse_args()
 if a.make_fixtures:
  spec={'kind':'original_editorial_washer_acceptance_spec_not_Kimi_task_result','declared_unit':'mm','outer_diameter_mm':40,'through_hole_diameter_mm':16,'height_mm':5}
  specfile=BASE/'kimi-official-audit.geometry-spec.json';specfile.write_text(json.dumps(spec,indent=2)+'\n')
  paths=[]
  for name,r in [('ring',8),('filled-hole-counterexample',0)]:
   f=BASE/f'kimi-official-audit.fixture-{name}.stl';write_stl(f,geometry(20,r,5,64));paths.append(f)
  rows=[audit(f,spec) for f in paths];assert rows[0]['accepted_for_this_limited_spec'] and not rows[1]['accepted_for_this_limited_spec'];assert rows[1]['checks']['edge_manifold'] and rows[1]['checks']['bounding_dimensions']
  report={'kind':'actual_local_STL_fixture_acceptance_demo_not_model_evaluation','model_calls':0,'paid_calls':0,'spec_file':str(specfile),'results':rows,'takeaway':'A watertight mesh with the right outer bounds can still fail the requested through-hole; inspect actual delivery against a task spec.'};out=BASE/'kimi-official-audit.geometry-results.json';out.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))
 elif a.stl and a.spec:print(json.dumps(audit(a.stl,json.loads(a.spec.read_text())),indent=2))
 else:p.error('--make-fixtures or both --stl and --spec required')
if __name__=='__main__':main()
