const size = ["Medium shot", "Close-up", "Wide shot", "Medium close-up", "Overhead shot"];
const move = ["slow push in", "static", "slow pan right", "slow pull back", "slow pan left"];
export function visualFor(chapterIndex, rowIndex) {
  const phrase = cues[chapterIndex]?.[rowIndex];
  if (!phrase) throw new Error(`Missing visual cue for chapter ${chapterIndex + 1}, line ${rowIndex + 1}`);
  const shot = size[(chapterIndex * 3 + rowIndex) % size.length];
  const lighting = ["soft morning window light", "cool desk lamp", "gentle indoor light", "muted afternoon light", "warm side light", "overcast daylight"];
  return { prompt: `${shot}: ${phrase}, ${lighting[(chapterIndex + rowIndex) % lighting.length]}`, camera: `${shot}, ${move[(chapterIndex + rowIndex) % move.length]}` };
}

export function visualCueCount(chapterIndex) { return cues[chapterIndex]?.length ?? 0; }
