/**
 * Generate the nginx `geo` block that tells the edge which addresses are a real search engine.
 *
 * The page limiter refuses anything over 5r/s with a 429, and on 2026-09-19 the host's own
 * logs showed that landing on Googlebot 20 times and on Bingbot as well. A 429 is not a
 * neutral "slow down" to a crawler: it is the signal a site sends when it is in distress, and
 * Google answers it by crawling less. On a site whose problem is that most of its pages are
 * not indexed, that is the wrong direction.
 *
 * The exemption is keyed on the published address ranges rather than on the User-Agent
 * string, because a User-Agent is a claim anyone can make: `curl -A Googlebot` would
 * otherwise buy an attacker the one thing the limiter exists to deny. `docs/anti-scraping.md`
 * takes the same position for the same reason.
 *
 * The ranges move, so this regenerates the block from the search engines' own files rather
 * than keeping a hand-written list that silently goes stale. Run it, commit the diff, and put
 * the result on the host; there is no runtime fetch.
 */

/** Where each engine publishes the addresses it crawls from. */
export const CRAWLER_SOURCES = [
  // Googlebot proper -- the crawler that builds the Search index.
  { name: "googlebot", url: "https://developers.google.com/search/apis/ipranges/googlebot.json" },
  // Google-InspectionTool and friends. Search Console's "Test live URL" fetches from here, so
  // leaving it out means the owner's own diagnostic can be the thing that gets a 429.
  { name: "google-special", url: "https://developers.google.com/static/crawling/ipranges/special-crawlers.json" },
  { name: "bingbot", url: "https://www.bing.com/toolbox/bingbot.json" },
];

/**
 * @param {{name: string, prefixes: string[]}[]} groups
 * @returns {string} an nginx http-context `geo` block
 */
export function crawlerGeoBlock(groups) {
  const total = groups.reduce((n, g) => n + g.prefixes.length, 0);
  if (!total) throw new Error("refusing to write an empty allowlist");
  const lines = [
    "# Generated by tools/nginx-crawler-ranges.mjs -- do not edit by hand.",
    "#",
    "# 1 means the address belongs to a search engine that published it. Consumed by the key",
    "# maps in mokaair-rate-limit.conf, which drop a verified crawler out of the page budget",
    "# and into a larger one of its own.",
    `# ${total} prefixes from ${groups.length} sources.`,
    "",
    "geo $mokaair_verified_crawler {",
    "    default 0;",
  ];
  for (const group of groups) {
    lines.push("", `    # ${group.name} (${group.prefixes.length})`);
    // Sorted so a regenerated file diffs only where the engine actually changed something.
    for (const prefix of [...group.prefixes].sort()) lines.push(`    ${prefix} 1;`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

/**
 * Pull the prefixes out of one published file. Google and Bing use the same shape:
 * `{prefixes: [{ipv4Prefix|ipv6Prefix: "..."}]}`.
 *
 * @param {unknown} payload
 * @returns {string[]}
 */
export function prefixesFrom(payload) {
  const rows = /** @type {{prefixes?: unknown}} */ (payload)?.prefixes;
  if (!Array.isArray(rows)) throw new Error("no prefixes array");
  const out = [];
  for (const row of rows) {
    const value = row?.ipv4Prefix ?? row?.ipv6Prefix;
    // A CIDR and nothing else: this text goes straight into a config nginx will parse.
    if (typeof value === "string" && /^[0-9a-fA-F:.]+\/\d{1,3}$/.test(value)) out.push(value);
  }
  if (!out.length) throw new Error("no usable prefixes");
  return out;
}

async function main() {
  const groups = [];
  for (const source of CRAWLER_SOURCES) {
    const response = await fetch(source.url, { redirect: "follow" });
    if (!response.ok) throw new Error(`${source.name}: HTTP ${response.status}`);
    groups.push({ name: source.name, prefixes: prefixesFrom(await response.json()) });
  }
  process.stdout.write(crawlerGeoBlock(groups));
}

// Only when run directly, so the test can import the pure halves without hitting the network.
if (process.argv[1]?.endsWith("nginx-crawler-ranges.mjs")) {
  main().catch((error) => { console.error(error.message); process.exit(1); });
}
